#!/bin/sh
# validate.sh — gate a candidate diff against the R0 blocklist + size cap.
#
# Usage:  validate.sh <path-to-diff>
#
# Exit codes:
#   0  diff is acceptable
#   2  diff touches a protected path or exceeds 50 changed lines
#   3  usage / IO error

set -eu

if [ $# -ne 1 ]; then
  echo "usage: $0 <diff-path>" >&2
  exit 3
fi
DIFF=$1
if [ ! -f "$DIFF" ]; then
  echo "no such file: $DIFF" >&2
  exit 3
fi

MAX_LINES="${MAX_LINES:-50}"

# Protected paths (POSIX-ish globs → grep patterns). Any file path in the diff
# that matches one of these blocks the PR.
#
# Rule of thumb: these are the files whose change would let shepherd rewrite
# its own rules. Keep the list narrow and document additions in CHANGELOG.
PROTECTED_RE='^(\.github/workflows/.*|\.shepherd\.yml|scripts/release\.sh|VERSION|.*\.env|.*\.pem|.*\.key)$'

# ---- Scan file headers --------------------------------------------------
# Unified-diff file lines look like:
#   --- a/<path>
#   +++ b/<path>
#   diff --git a/<path> b/<path>
# Extract every <path>, dedupe, test each against the blocklist.
touched=$(awk '
  /^--- a\// { sub(/^--- a\//, ""); if ($0 != "/dev/null") print }
  /^\+\+\+ b\// { sub(/^\+\+\+ b\//, ""); if ($0 != "/dev/null") print }
  /^diff --git a\// {
    sub(/^diff --git a\//, "")
    sub(/ b\/.*$/, "")
    print
  }
' "$DIFF" | sort -u)

if [ -z "$touched" ]; then
  echo "validate: no file paths found in diff" >&2
  exit 2
fi

blocked=$(printf '%s\n' "$touched" | grep -E "$PROTECTED_RE" || true)
if [ -n "$blocked" ]; then
  echo "validate: diff touches protected path(s):" >&2
  printf '  %s\n' "$blocked" >&2
  exit 2
fi

# ---- Size cap -----------------------------------------------------------
# Lockfile paths are exempt from the cap: they are regenerated by the
# ecosystem's package manager (npm, pip, go) in regen-lockfile.sh, not by
# the agent. A 100-line package-lock.json diff is safe-by-construction.
# The cap still applies to all other paths (= the agent's attack surface).
LOCKFILE_RE='^(package-lock[.]json|yarn[.]lock|pnpm-lock[.]yaml|poetry[.]lock|Pipfile[.]lock|go[.]sum|Cargo[.]lock)$'

non_lockfile_lines=$(awk -v re="$LOCKFILE_RE" '
  /^diff --git a\// {
    path = $0
    sub(/^diff --git a\//, "", path)
    sub(/ b\/.*$/, "", path)
    in_lock = (path ~ re) ? 1 : 0
    next
  }
  /^--- / || /^\+\+\+ / { next }
  !in_lock && /^[+-]/    { n++ }
  END { print n+0 }
' "$DIFF")

if [ "$non_lockfile_lines" -gt "$MAX_LINES" ]; then
  echo "validate: non-lockfile diff is $non_lockfile_lines changed lines, cap is $MAX_LINES" >&2
  exit 2
fi

lockfile_lines=$(awk -v re="$LOCKFILE_RE" '
  /^diff --git a\// {
    path = $0
    sub(/^diff --git a\//, "", path)
    sub(/ b\/.*$/, "", path)
    in_lock = (path ~ re) ? 1 : 0
    next
  }
  /^--- / || /^\+\+\+ / { next }
  in_lock && /^[+-]/     { n++ }
  END { print n+0 }
' "$DIFF")

file_count=$(printf '%s' "$touched" | wc -l | tr -d ' ')
echo "validate: OK (non-lockfile=$non_lockfile_lines/$MAX_LINES; lockfile=$lockfile_lines exempt; files=$file_count)"
